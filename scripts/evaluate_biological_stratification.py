def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Evaluate MuSRNet biological stratification")
    parser.add_argument("--config", required=True)
    parser.add_argument("--pred", action="append", required=True, help="model_name=path/to/predictions.csv")
    parser.add_argument("--sample-csv", required=True)
    parser.add_argument("--pdb-dir", required=True)
    parser.add_argument("--out-dir", required=True)
    parser.add_argument("--domain-annotations", default="data/domain_annotations.csv", help="CSV generated by scripts/fetch_domain_annotations.py")
    parser.add_argument("--resolution-cache", default="data/resolution_cache.json")
    parser.add_argument("--dssp-cache-dir", default="data/dssp_cache")
    parser.add_argument("--dssp-download-dir", default="data/dssp_downloads")
    parser.add_argument("--rsa-threshold", type=float, default=0.20)
    parser.add_argument("--high-resolution-threshold", type=float, default=2.0)
    parser.add_argument("--long-protein-threshold", default="auto")
    parser.add_argument("--bootstrap-iters", type=int, default=10000)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--reference")
    parser.add_argument("--candidate")
    parser.add_argument("--num-workers", type=int, default=1, help="Number of parallel workers for fetching DSSP/resolution")
    return parser.parse_args()


def parse_pred_arg(text: str) -> tuple[str, Path]:
    if "=" not in text:
        raise ValueError(f"Invalid --pred format: {text}. Expected model_name=path/to/predictions.csv")
    model_name, path_str = text.split("=", 1)
    model_name = model_name.strip()
    path = Path(path_str.strip())
    if not model_name or not path_str.strip():
        raise ValueError(f"Invalid --pred format: {text}. Expected model_name=path/to/predictions.csv")
    return model_name, path


def read_predictions(pred_args: list[str]) -> dict[str, pd.DataFrame]:
    tables: dict[str, pd.DataFrame] = {}
    for item in pred_args:
        model_name, path = parse_pred_arg(item)
        if not path.exists():
            raise FileNotFoundError(f"Prediction CSV not found: {path}")
        df = pd.read_csv(path)
        if df.empty:
            raise ValueError(f"Empty prediction table: {path}")
        tables[model_name] = normalize_prediction_columns(df)
    return tables


def load_sample_table(path: str | Path) -> pd.DataFrame:
    sample_df = pd.read_csv(path)
    missing = [col for col in REQUIRED_SAMPLE_COLUMNS if col not in sample_df.columns]
    if missing:
        raise ValueError(f"Missing required sample CSV columns: {missing}")
    sample_df = sample_df.copy()
    sample_df["sample_id"] = sample_df["sample_id"].astype(str)
    sample_df["cluster_id_30"] = sample_df["cluster_id_30"].astype(str)
    for column in ["wt_pdb_id", "wt_chain_id", "mut_pdb_id", "mut_chain_id", "wt_aa_type", "mut_aa_type", "release_date"]:
        sample_df[column] = sample_df[column].astype(str)
    return sample_df


def merge_prediction_with_samples(pred_df: pd.DataFrame, sample_df: pd.DataFrame) -> pd.DataFrame:
    sample_cols = [
        "sample_id",
        "cluster_id_30",
        "wt_pdb_id",
        "wt_chain_id",
        "mut_pdb_id",
        "mut_chain_id",
        "mut_pos_seq_index",
        "mut_pos_pdb_number",
        "wt_aa_type",
        "mut_aa_type",
        "wt_sequence",
        "mut_sequence",
        "release_date",
    ]
    sample_meta = sample_df[sample_cols].drop_duplicates("sample_id")
    merged = pred_df.merge(sample_meta, on="sample_id", how="left", suffixes=("", "_sample"))
    if merged["wt_pdb_id"].isna().any():
        missing_ids = sorted(set(merged.loc[merged["wt_pdb_id"].isna(), "sample_id"].astype(str)))
        raise ValueError(f"Missing sample metadata for sample_id values: {missing_ids[:10]}")
    if "cluster_id_30_sample" in merged.columns:
        merged["cluster_id_30"] = merged["cluster_id_30"].fillna(merged["cluster_id_30_sample"]).astype(str)
        merged = merged.drop(columns=["cluster_id_30_sample"])
    return merged


def make_annotation_args(args: argparse.Namespace, warnings: list[str], long_threshold_value: float) -> argparse.Namespace:
    return argparse.Namespace(
        domain_annotations=args.domain_annotations,
        domain_source_priority=("CATH", "SCOP", "Pfam", "InterPro"),
        resolution_cache=args.resolution_cache,
        dssp_cache_dir=args.dssp_cache_dir,
        rsa_threshold=args.rsa_threshold,
        high_resolution_threshold=args.high_resolution_threshold,
        long_protein_threshold_value=long_threshold_value,
        dssp_download_dir=Path(args.dssp_download_dir),
        warnings=warnings,
    )


def write_warnings(path: Path, warnings: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        for message in warnings:
            handle.write(message + "\n")


def write_summary_csv(path: Path, rows: list[dict[str, object]]) -> None:
    df = pd.DataFrame(rows)
    df.to_csv(path, index=False)


def make_wide_table(long_df: pd.DataFrame) -> pd.DataFrame:
    wide = long_df.pivot_table(
        index=["model_name", "factor", "group"],
        columns="metric",
        values=[
            "sample_mean",
            "cluster_mean",
            "sample_weighted_cluster_mean",
            "residue_weighted_cluster_mean",
            "n_samples",
            "n_clusters",
            "n_residues",
            "n_valid_samples",
            "bootstrap_ci_low",
            "bootstrap_ci_high",
        ],
        aggfunc="first",
    )
    wide.columns = [f"{left}__{right}" for left, right in wide.columns]
    return wide.reset_index()


def plot_factor_metric(long_df: pd.DataFrame, factor: str, metric: str, out_path: Path) -> None:
    plot_df = long_df[(long_df["factor"] == factor) & (long_df["metric"] == metric)].copy()
    if plot_df.empty:
        return
    groups = list(plot_df["group"].drop_duplicates())
    models = list(plot_df["model_name"].drop_duplicates())
    x = np.arange(len(groups), dtype=np.float64)
    width = 0.8 / max(len(models), 1)

    fig, ax = plt.subplots(figsize=(max(6.0, len(groups) * 1.3), 4.5))
    for idx, model_name in enumerate(models):
        model_df = plot_df[plot_df["model_name"] == model_name].set_index("group").reindex(groups)
        centers = x - 0.4 + width / 2.0 + idx * width
        heights = model_df["cluster_mean"].to_numpy(dtype=np.float64)
        low = model_df["bootstrap_ci_low"].to_numpy(dtype=np.float64)
        high = model_df["bootstrap_ci_high"].to_numpy(dtype=np.float64)
        yerr = np.vstack([
            np.where(np.isfinite(low), np.clip(heights - low, a_min=0.0, a_max=None), np.nan),
            np.where(np.isfinite(high), np.clip(high - heights, a_min=0.0, a_max=None), np.nan),
        ])
        ax.bar(centers, heights, width=width, label=model_name)
        if np.isfinite(yerr).any():
            ax.errorbar(centers, heights, yerr=yerr, fmt="none", ecolor="black", capsize=3, linewidth=1)

    ax.set_xticks(x)
    ax.set_xticklabels(groups, rotation=30, ha="right")
    ax.set_ylabel(metric)
    ax.set_title(f"{factor}: {metric}")
    ax.legend(frameon=False)
    fig.tight_layout()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, dpi=200)
    plt.close(fig)


def determine_allosteric_status(
    pairwise_df: pd.DataFrame | None,
    reference: str | None,
    candidate: str | None,
) -> tuple[str, str]:
    if not reference or not candidate or pairwise_df is None or pairwise_df.empty:
        return "not_assessed", "not_assessed"

    shell4 = pairwise_df[pairwise_df["metric"] == "mae_shell_4"]
    non_local = pairwise_df[pairwise_df["metric"].isin(["non_local_f1", "non_local_recall"])]
    if non_local.empty:
        return "do_not_claim_allosteric_improvement_class_not_assessed", "not_assessed"

    shell4_improved = bool((shell4["mean_diff"] < 0).any()) if not shell4.empty else False
    non_local_improved = bool((non_local["mean_diff"] > 0).any())
    if shell4_improved and non_local_improved:
        return "limited_allosteric_claim_possible", "assessed"
    return "do_not_claim_allosteric_improvement", "assessed"


def main() -> None:
    args = parse_args()
    config = load_yaml(args.config)
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    warnings: list[str] = []

    prediction_tables = read_predictions(args.pred)
    sample_df = load_sample_table(args.sample_csv)

    evaluated_sample_ids = sorted({sample_id for df in prediction_tables.values() for sample_id in df["sample_id"].astype(str).unique()})
    sample_subset = sample_df[sample_df["sample_id"].isin(evaluated_sample_ids)].copy()
    if sample_subset.empty:
        raise ValueError("No evaluated samples overlap between prediction CSVs and sample CSV")

    if args.long_protein_threshold == "auto":
        long_threshold_value = float(sample_subset["wt_sequence"].astype(str).str.len().median())
    else:
        long_threshold_value = float(args.long_protein_threshold)

    ann_args = make_annotation_args(args, warnings, long_threshold_value)
    annotations_df = build_biological_annotations(sample_subset.drop_duplicates("sample_id"), args.pdb_dir, ann_args, num_workers=args.num_workers)
    annotations_df.to_csv(out_dir / "biological_annotations.csv", index=False)

    eval_cfg = config.get("eval", {})
    response_threshold = float(eval_cfg.get("response_threshold", 0.5))
    displacement_threshold = float(eval_cfg.get("displacement_threshold", 1.0))
    radius_threshold = float(eval_cfg.get("radius_threshold", 8.0))

    sample_metric_tables: list[pd.DataFrame] = []
    for model_name, pred_df in prediction_tables.items():
        merged = merge_prediction_with_samples(pred_df, sample_subset)
        metrics_df = compute_sample_metrics(
            merged,
            response_threshold=response_threshold,
            displacement_threshold=displacement_threshold,
            radius_threshold=radius_threshold,
            warnings=warnings,
        )
        metrics_df["model_name"] = model_name
        metrics_df = metrics_df.merge(annotations_df, on=["sample_id", "cluster_id_30"], how="left")
        sample_metric_tables.append(metrics_df)

    sample_metrics_df = pd.concat(sample_metric_tables, ignore_index=True)
    sample_metrics_df.to_csv(out_dir / "sample_metrics_with_strata.csv", index=False)

    factor_columns = [
        "exposure_group",
        "substitution_size_group",
        "charge_group",
        "charge_binary_group",
        "glypro_group",
        "gly_group",
        "pro_group",
        "secondary_structure_group",
        "length_group",
        "resolution_group",
        "domain_group",
    ]
    metric_columns = [
        "global_mae",
        "shell_mae",
        "mae_shell_0",
        "mae_shell_1",
        "mae_shell_2",
        "mae_shell_3",
        "mae_shell_4",
        "perturbed_auroc",
        "perturbed_auprc",
        "radius_mae",
        "class_correct",
        "class_macro_f1",
        "non_local_f1",
        "non_local_recall",
    ]
    available_metrics = [metric for metric in metric_columns if metric in sample_metrics_df.columns]
    long_df, cluster_metric_df = compute_stratified_metrics(
        sample_metrics_df=sample_metrics_df,
        factor_columns=factor_columns,
        metric_columns=available_metrics,
        bootstrap_iters=args.bootstrap_iters,
        seed=args.seed,
        warnings=warnings,
    )
    long_df.to_csv(out_dir / "stratified_metrics_long.csv", index=False)
    make_wide_table(long_df).to_csv(out_dir / "stratified_metrics_wide.csv", index=False)

    pairwise_df: pd.DataFrame | None = None
    if args.reference or args.candidate:
        if not args.reference or not args.candidate:
            raise ValueError("Both --reference and --candidate are required together")
        if args.reference not in prediction_tables or args.candidate not in prediction_tables:
            raise ValueError("Reference/candidate model names must be present in --pred arguments")
        pairwise_df = compute_pairwise_stratified_diffs(
            cluster_metric_df=cluster_metric_df,
            reference=args.reference,
            candidate=args.candidate,
            bootstrap_iters=args.bootstrap_iters,
            seed=args.seed,
            warnings=warnings,
        )
        pairwise_df.to_csv(out_dir / "pairwise_stratified_diff.csv", index=False)

    figures_dir = out_dir / "figures"
    for factor in factor_columns:
        plot_factor_metric(long_df, factor, "shell_mae", figures_dir / f"{factor}_shell_mae_cluster_mean.png")
        plot_factor_metric(long_df, factor, "perturbed_auprc", figures_dir / f"{factor}_perturbed_auprc_cluster_mean.png")
        plot_factor_metric(long_df, factor, "mae_shell_4", figures_dir / f"{factor}_mae_shell_4_cluster_mean.png")

    allosteric_claim_status, non_local_class_status = determine_allosteric_status(pairwise_df, args.reference, args.candidate)

    domain_group_counts = (
        annotations_df["domain_group"]
        .value_counts(dropna=False)
        .to_dict()
        if "domain_group" in annotations_df.columns
        else {}
    )

    domain_source_counts = (
        annotations_df["domain_source_used"]
        .value_counts(dropna=False)
        .to_dict()
        if "domain_source_used" in annotations_df.columns
        else {}
    )

    summary = {
        "config": str(args.config),
        "prediction_files": {name: str(path) for name, path in [parse_pred_arg(item) for item in args.pred]},
        "sample_csv": str(args.sample_csv),
        "pdb_dir": str(args.pdb_dir),
        "domain_annotations": args.domain_annotations,
        "domain_group_counts": domain_group_counts,
        "domain_source_counts": domain_source_counts,
        "resolution_cache": str(args.resolution_cache),
        "dssp_cache_dir": str(args.dssp_cache_dir),
        "rsa_threshold": args.rsa_threshold,
        "high_resolution_threshold": args.high_resolution_threshold,
        "long_protein_threshold": args.long_protein_threshold,
        "long_protein_threshold_value": long_threshold_value,
        "bootstrap_iters": args.bootstrap_iters,
        "seed": args.seed,
        "reference": args.reference,
        "candidate": args.candidate,
        "n_models": len(prediction_tables),
        "n_samples": int(sample_metrics_df["sample_id"].nunique()),
        "n_clusters": int(sample_metrics_df["cluster_id_30"].nunique()),
        "models": sorted(prediction_tables.keys()),
        "factors": factor_columns,
        "available_metrics": available_metrics,
        "allosteric_claim_status": allosteric_claim_status,
        "non_local_class_status": non_local_class_status,
        "stratified_metrics": long_df.to_dict(orient="records"),
        "pairwise_stratified_diffs": [] if pairwise_df is None else pairwise_df.to_dict(orient="records"),
        "warnings": warnings,
    }
    with (out_dir / "summary.json").open("w", encoding="utf-8") as handle:
        json.dump(summary, handle, indent=2)
    write_warnings(out_dir / "warnings.txt", warnings)

    print("Biological stratification summary written to:", out_dir / "summary.json")
    print("Do not claim robust allosteric/non-local response improvement unless mae_shell_4 and non-local class metrics improve.")


if __name__ == "__main__":
    main()
